import assert from 'node:assert/strict';
import { periodRange, movePeriod, requestDates, attendanceRows, fetchAllRequests } from '../src/lib/empleado/presentation.mjs';
assert.deepEqual(periodRange('2026-01-01','week'),{from:'2025-12-29',to:'2026-01-04'});
assert.equal(periodRange('2024-02-10','month').to,'2024-02-29');
assert.equal(movePeriod('2026-01-31','month',1),'2026-02-01');
assert.equal(movePeriod('2026-12-31','year',1),'2027-01-01');
const request = { fecha_inicio:'2026-10-23', fecha_fin:'2026-10-26', dias_trabajo:'Lunes,Martes,Miércoles,Jueves,Viernes', descuenta_vacaciones:1, estado:'Aprobado' };
assert.equal(requestDates(request,['2026-10-26']).duration,'1 día hábil');
assert.match(requestDates(request,['2026-10-26']).back,/27/);
assert.equal(requestDates(request,null).duration,'4 días naturales');
assert.equal(requestDates({...request,dias_trabajo:''},[]).back,null);
assert.equal(requestDates({...request,fecha_fin:'2026-10-01'},[]).duration,null);
assert.equal(attendanceRows({entradas_salidas:{registros:[{fecha:'2026-10-23',estado:'Cerrado'}]}})[0].attendanceStatus,'Sin clasificar');
const joined=attendanceRows({entradas_salidas:{registros:[{fecha:'2026-10-23',estado:'Cerrado'}]},asistencias:{historial:[{fecha:'2026-10-23',estado:'Retardo'},{fecha:'2026-10-22',estado:'Ausente'}]}});
assert.deepEqual(joined.map(row=>row.attendanceStatus),['Tardanza','Ausente']);
assert.equal(requestDates({fecha_inicio:'2026-10-26',fecha_fin:'2026-10-28'},[]).range, 'Lun 26 – Mié 28 oct 2026');
assert.equal(requestDates({fecha_inicio:'2026-12-31',fecha_fin:'2027-01-02'},[]).range, 'Jue 31 dic 2026 – Sáb 2 ene 2027');
let pages=0;
const data=await fetchAllRequests(async()=>({results:[{id:++pages}],total:3}),101);
assert.equal(data.length,3);
await assert.rejects(()=>fetchAllRequests(async()=>({results:[{id:1}],total:3}),101),/completar/);
