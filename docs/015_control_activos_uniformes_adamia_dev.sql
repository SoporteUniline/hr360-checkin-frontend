USE `adamia_dev`;
SET NAMES utf8mb4;

CREATE TABLE cau_articulos (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  id_empresa INT NOT NULL,
  tipo ENUM('activo','uniforme') NOT NULL,
  nombre VARCHAR(180) NOT NULL,
  codigo VARCHAR(80) NOT NULL,
  categoria VARCHAR(100) NOT NULL,
  marca VARCHAR(100) NULL,
  modelo VARCHAR(150) NULL,
  numero_serie VARCHAR(120) NULL COMMENT 'Normalizar cadena vacia a NULL',
  talla VARCHAR(30) NULL,
  color VARCHAR(60) NULL,
  retornable BOOLEAN NOT NULL DEFAULT TRUE,
  stock_minimo INT UNSIGNED NOT NULL DEFAULT 0,
  costo_referencia DECIMAL(12,2) NOT NULL DEFAULT 0,
  meses_reposicion SMALLINT UNSIGNED NOT NULL DEFAULT 0,
  activo BOOLEAN NOT NULL DEFAULT TRUE,
  created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  created_by INT NOT NULL,
  updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
  updated_by INT NULL,
  version INT UNSIGNED NOT NULL DEFAULT 1,
  PRIMARY KEY (id),
  UNIQUE KEY uq_cau_articulos_empresa_id (id_empresa, id),
  CONSTRAINT ck_cau_articulos_version CHECK (version > 0),
  UNIQUE KEY uq_cau_art_codigo (id_empresa, codigo),
  UNIQUE KEY uq_cau_art_serie (id_empresa, numero_serie),
  KEY ix_cau_art_busqueda (id_empresa, tipo, activo, nombre),
  CONSTRAINT ck_cau_art_costo CHECK (costo_referencia >= 0),
  CONSTRAINT ck_cau_art_bool CHECK (retornable IN (0,1) AND activo IN (0,1)),
  CONSTRAINT ck_cau_art_codigo CHECK (CHAR_LENGTH(TRIM(codigo)) > 0),
  CONSTRAINT ck_cau_art_serie CHECK (numero_serie IS NULL OR CHAR_LENGTH(TRIM(numero_serie)) > 0),
  CONSTRAINT fk_cau_articulos_empresa FOREIGN KEY (id_empresa) REFERENCES empresas (id_empresa) ON DELETE RESTRICT ON UPDATE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

