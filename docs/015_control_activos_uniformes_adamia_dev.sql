CREATE TABLE cau_solicitudes (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  id_empresa INT NOT NULL,
  id_empleado INT NOT NULL,
  id_entrega_detalle BIGINT UNSIGNED NULL,
  tipo ENUM('falla_equipo','cambio_talla','reposicion','otro') NOT NULL,
  descripcion TEXT NOT NULL,
  estado ENUM('pendiente','en_proceso','resuelta','rechazada') NOT NULL DEFAULT 'pendiente',
  id_usuario_responsable INT NULL,
  respuesta TEXT NULL,
  fecha_resolucion DATETIME(6) NULL,
  resolved_by INT NULL,
  created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  created_by INT NOT NULL,
  updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
  updated_by INT NULL,
  version INT UNSIGNED NOT NULL DEFAULT 1,
  PRIMARY KEY (id),
  UNIQUE KEY uq_cau_solicitudes_empresa_id (id_empresa, id),
  CONSTRAINT ck_cau_solicitudes_version CHECK (version > 0),
  KEY ix_cau_sol_estado (id_empresa, estado, created_at),
  KEY ix_cau_sol_empleado (id_empresa, id_empleado, created_at),
  CONSTRAINT ck_cau_sol_descripcion CHECK (CHAR_LENGTH(TRIM(descripcion)) > 0),
  CONSTRAINT ck_cau_sol_cierre CHECK ((estado IN ('pendiente','en_proceso') AND fecha_resolucion IS NULL AND resolved_by IS NULL) OR (estado IN ('resuelta','rechazada') AND fecha_resolucion IS NOT NULL AND resolved_by IS NOT NULL AND respuesta IS NOT NULL AND CHAR_LENGTH(TRIM(respuesta)) > 0)),
  CONSTRAINT fk_solicitudes_entrega FOREIGN KEY (id_empresa, id_entrega_detalle) REFERENCES cau_entrega_detalle (id_empresa, id) ON DELETE RESTRICT ON UPDATE RESTRICT,
