CREATE TABLE cau_operaciones (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  id_empresa INT NOT NULL,
  tipo ENUM('articulo_guardar','articulo_archivar','entrada','ajuste','traslado','entrega','devolucion','cambio_uniforme','reversion','acuse','mantenimiento_abrir','mantenimiento_cerrar','paquete_guardar','tallas_guardar','solicitud_crear','solicitud_resolver') NOT NULL,
  idempotency_key VARCHAR(128) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  request_hash CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT 'SHA-256 del payload canonico y contexto de la operacion',
  estado ENUM('procesando','completada','fallida') NOT NULL DEFAULT 'procesando',
  resultado_json JSON NULL,
  http_status SMALLINT UNSIGNED NULL,
  completed_at DATETIME(6) NULL,
  created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  created_by INT NOT NULL,
  updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
  updated_by INT NULL,
  version INT UNSIGNED NOT NULL DEFAULT 1,
  PRIMARY KEY (id),
  UNIQUE KEY uq_cau_operaciones_empresa_id (id_empresa, id),
  CONSTRAINT ck_cau_operaciones_version CHECK (version > 0),
  UNIQUE KEY uq_cau_ope_idempotencia (id_empresa, idempotency_key),
  KEY ix_cau_ope_estado (id_empresa, estado, created_at),
  CONSTRAINT ck_cau_ope_http CHECK (http_status IS NULL OR http_status BETWEEN 100 AND 599),
  CONSTRAINT ck_cau_ope_cierre CHECK (estado = 'procesando' OR completed_at IS NOT NULL),
  CONSTRAINT fk_cau_operaciones_empresa FOREIGN KEY (id_empresa) REFERENCES empresas (id_empresa) ON DELETE RESTRICT ON UPDATE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE cau_entregas (
