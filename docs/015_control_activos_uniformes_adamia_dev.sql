  CONSTRAINT fk_entregas_reversion FOREIGN KEY (id_empresa, id_operacion_cancelacion) REFERENCES cau_operaciones (id_empresa, id) ON DELETE RESTRICT ON UPDATE RESTRICT,
  CONSTRAINT fk_cau_entregas_empresa FOREIGN KEY (id_empresa) REFERENCES empresas (id_empresa) ON DELETE RESTRICT ON UPDATE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

